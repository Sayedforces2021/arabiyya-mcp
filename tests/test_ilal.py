"""الحالات المعيارية لمحرّك الإعلال: python tests/test_ilal.py"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import sarf_ilal as I
tests=[("فَعَلَ","قول","verb","قَالَ"),("يَفْعُلُ","قول","verb","يَقُولُ"),("يَفْعِلُ","بيع","verb","يَبِيعُ"),
("مَفْعُول","قول","noun","مَقُول"),("مَفْعُول","بيع","noun","مَبِيع"),("فاعِل","قول","noun","قائِل"),("فاعِل","بيع","noun","بائِع"),
("مَفْعَل","قوم","noun","مَقام"),("أَفْعَلَ","قوم","verb","أَقامَ"),("اِسْتَفْعَلَ","قوم","verb","اِسْتَقامَ"),
("فَعَلَ","دعو","verb","دَعا"),("فَعَلَ","رمي","verb","رَمَى"),("فاعِل","دعو","noun","داعِي"),("فاعِلٌ","دعو","noun","داعٍ"),
("فُعال","دعو","noun","دُعاء"),("فِعال","بني","noun","بِناء"),("مَفْعُول","رمي","noun","مَرْمِيّ"),("مَفْعُول","دعو","noun","مَدْعُوّ"),
("فَيْعِل","سود","noun","سَيِّد"),("مِفْعال","وزن","noun","مِيزان"),("مِفْعاد","وعد","noun","ميعاد"),("مُفْعِل","يسر","noun","مُوسِر"),
("يَفْعِلُ","وعد","verb","يَعِدُ"),("اِفْتَعَلَ","وصل","verb","اِتَّصَلَ"),("اِفْتَعَلَ","صبر","verb","اِصْطَبَرَ"),("اِفْتَعَلَ","زجر","verb","اِزْدَجَرَ"),
("اِفْتَعَلَ","دعو","verb","اِدَّعَى"),("فَعَلَ","مدد","verb","مَدَّ"),("يَفْعُلُ","مدد","verb","يَمُدُّ"),("فاعِل","مدد","noun","مادّ"),("أَفْعَل","شدد","noun","أَشَدّ"),
("أَفْعَلَ","ءمن","verb","آمَنَ"),("إِفْعال","ءمن","noun","إِيمان"),("إِفْعال","قوم","noun","إِقامَة"),("اِسْتِفْعال","قوم","noun","اِسْتِقامَة"),
("فَعَل","طلل","noun","طَلَل"),("أَفْعَل","قوم","noun","أَقْوَم"),("مِفْعَل","قول","noun","مِقْوَل"),("فَعَلَ","طوي","verb","طَوَى"),("فَعِلَ","رضو","verb","رَضِيَ"),
("فَعْل","قول","noun","قَوْل"),("مَفْعِل","وعد","noun","مَوْعِد"),("يَفْعَلُ","خوف","verb","يَخافُ")]
ok=0
for wazn,root,pos,exp in tests:
    ctx={"pos":pos}
    if wazn.startswith("اِفْتَ"): ctx["form"]="VIII"
    if wazn in ("إِفْعال","اِسْتِفْعال"): ctx["masdar_ifala"]=True
    if wazn.startswith("مِفْعَل") : ctx["pattern_kind"]="ala"
    if pos!="verb" and wazn.startswith("أَفْعَل"): ctx["no_naql"]=True
    if wazn=="مِفْعَل": ctx["no_naql"]=True
    tpl=I.parse_wazn(wazn)
    r=I.derive(tpl, root, ctx)
    asl,surf,steps=r
    good = I.bare(surf)==I.bare(exp) and (("ّ" in surf)==("ّ" in exp))
    ok+=good
    print('OK ' if good else 'BAD', wazn, root, asl,'→',surf,'| exp',exp, '|', ' ⟵ '.join(s['الخطوة'][:40] for s in steps) if not good else len(steps))
print(ok,'/',len(tests))

assert ok == len(tests)
