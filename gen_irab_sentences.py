#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""مولّد جمل مُعرَبة لتدريب محلّل الإعراب (train_irab.py --gen) على أبوابٍ يقلّ مثالها في ماساق أو يلتبس بلا شكل:
المفعول معه (9 أمثلة فقط في ماساق، دون حدّ القبول)، ولام الأمر ولام التعليل، وفاء السببية وواو المعية مع المضارع،
والنثر البسيط بترتيباته (فعل فاعل مفعول، وتقديم المفعول، والمبتدأ وخبره الفعلي)، ونائب الفاعل، والحال.

الوسوم بأسماء ماساق نفسها (المدوّنة M)، فلا تُنشئ نظام وسوم جديدًا:
واو المعية وفاء السببية «حرف غير عامل»، ولام التعليل «حرف جر»، ولام الأمر «حرف جزم»، والفعل الواقع خبرًا «ش:خبر» مع «فعل ماضٍ».
وكل مثالٍ له مقابل يخالفه في الوسم (العطف مقابل المعية، والجزم مقابل النصب)، والفارق بينهما الحركة، أو المعنى حين تُحذف الحركة.

لا يستعمل كلمةً من المجموعة الذهبية (eval/gold_irab/gold.jsonl) إلا حروف المعاني، حتى يبقى القياس عليها اختبارًا لا حفظًا.
التشغيل:  python gen_irab_sentences.py [--out ~/.sarf/corpora/gen_irab.jsonl] [--per 250]"""
import argparse, itertools, json, random, re
from pathlib import Path

MARKS = re.compile("[ً-ْٰـ]")
FUNCTION_WORDS = {"لا", "في", "إلى", "من"}


def bare(w):
    return MARKS.sub("", w).replace("ٱ", "ا")


def with_case(w, mark):
    """تبديل حركة الآخر: «الْبَابَ» ← «الْبَابُ»."""
    i = max(w.rfind(c) for c in "ُ َ ِ".split())
    return w[:i] + mark + w[i + 1:]


def jazm(stem, next_word):
    """المضارع المجزوم والأمر: سكون، ويُكسر لالتقاء الساكنين قبل «ال»."""
    return stem + ("ِ" if next_word and bare(next_word).startswith("ال") else "ْ")


# الفعل: (الماضي، المبني للمجهول، المضارع للغائب بلا حركة آخر، المضارع للمخاطب، الأمر، مفعولاته)
VERBS = [
    ("حَمَلَ", "حُمِلَ", "يَحْمِل", "تَحْمِل", "احْمِل", ["الْحَقِيبَةَ", "الْحَطَبَ", "الصُّنْدُوقَ"]),
    ("فَتَحَ", "فُتِحَ", "يَفْتَح", "تَفْتَح", "افْتَح", ["الْبَابَ", "النَّافِذَةَ", "الصُّنْدُوقَ"]),
    ("غَسَلَ", "غُسِلَ", "يَغْسِل", "تَغْسِل", "اغْسِل", ["الثَّوْبَ", "الْإِنَاءَ"]),
    ("زَرَعَ", "زُرِعَ", "يَزْرَع", "تَزْرَع", "ازْرَع", ["الْأَرْضَ", "الْقَمْحَ", "الشَّجَرَ"]),
    ("رَسَمَ", "رُسِمَ", "يَرْسُم", "تَرْسُم", "ارْسُم", ["الصُّورَةَ", "الْخَرِيطَةَ"]),
    ("حَفِظَ", "حُفِظَ", "يَحْفَظ", "تَحْفَظ", "احْفَظ", ["الْقَصِيدَةَ", "السُّورَةَ", "الْحَدِيثَ"]),
    ("جَمَعَ", "جُمِعَ", "يَجْمَع", "تَجْمَع", "اجْمَع", ["الثِّمَارَ", "الْحَطَبَ"]),
    ("لَبِسَ", "لُبِسَ", "يَلْبَس", "تَلْبَس", "الْبَس", ["الثَّوْبَ", "الْعِمَامَةَ"]),
    ("سَمِعَ", "سُمِعَ", "يَسْمَع", "تَسْمَع", "اسْمَع", ["الْخَبَرَ", "الْقَصِيدَةَ"]),
    ("تَرَكَ", "تُرِكَ", "يَتْرُك", "تَتْرُك", "اتْرُك", ["الْعَمَلَ", "الْبَابَ"]),
    ("صَنَعَ", "صُنِعَ", "يَصْنَع", "تَصْنَع", "اصْنَع", ["الطَّعَامَ", "الصُّنْدُوقَ"]),
]
SUBJ = ["التَّاجِرُ", "الْفَلَّاحُ", "الْجُنْدِيُّ", "الصَّيَّادُ", "الْمُسَافِرُ", "الْأَمِيرُ", "الشَّيْخُ", "الْوَلَدُ",
        "الْقَائِدُ", "الْبَحَّارُ", "الْخَادِمُ", "الصَّانِعُ"]
# أفعال لازمة للسير والمكث، وماضيها للمتكلم
MOTION = [("سَارَ", "سِرْتُ"), ("مَشَى", "مَشَيْتُ"), ("رَجَعَ", "رَجَعْتُ"), ("خَرَجَ", "خَرَجْتُ"),
          ("انْطَلَقَ", "انْطَلَقْتُ"), ("عَادَ", "عُدْتُ"), ("جَلَسَ", "جَلَسْتُ"), ("تَنَزَّهَ", "تَنَزَّهْتُ")]
# ما يُصاحَب ولا يشارك في الفعل: «سار الجيش والنيلَ»
MAIYYA = [["النِّيلَ"], ["الطَّرِيقَ"], ["الشَّاطِئَ"], ["النَّهْرَ"], ["الْجَبَلَ"], ["الْقَمَرَ"], ["السَّاحِلَ"], ["الْجِدَارَ"],
          ["طُلُوعَ", "الْفَجْرِ"], ["غُرُوبَ", "الشَّمْسِ"], ["ضَوْءَ", "الْقَمَرِ"]]
HAL = ["مَسْرُورًا", "فَرِحًا", "غَاضِبًا", "حَزِينًا", "مُسْرِعًا", "رَاكِبًا", "مُتْعَبًا"]
RESULT = ["تَنْجَحَ", "تَرْبَحَ", "تَسْلَمَ", "تَفْرَحَ", "تَغْنَمَ"]   # مضارع منصوب بعد فاء السببية


def gen():
    """يعيد [(الظاهرة، [(الكلمة المشكولة، [الوسوم])...])]."""
    out = []
    def add(kind, *pairs):
        out.append((kind, [(w, list(ls)) for w, ls in pairs]))

    for (v, v1), s, n in itertools.product(MOTION, SUBJ, MAIYYA):
        mm = [("وَ" + n[0], ["حرف غير عامل", "مفعول معه"])] + [(x, ["مضاف إليه"]) for x in n[1:]]
        add("مفعول معه", (v, ["فعل ماضٍ"]), (s, ["فاعل"]), *mm)
        add("مفعول معه", (v1, ["فاعل", "فعل ماضٍ"]), *mm)
    for (v, _), s, s2 in itertools.product(MOTION, SUBJ, SUBJ):
        if s != s2:
            add("عطف اسم مرفوع (مقابل المعية)", (v, ["فعل ماضٍ"]), (s, ["فاعل"]), ("وَ" + s2, ["حرف عطف", "اسم معطوف"]))
    for (p, ps, m3, m2, imp, objs), s in itertools.product(VERBS, SUBJ):
        for o in objs:
            add("نثر: فعل فاعل مفعول", (p, ["فعل ماضٍ"]), (s, ["فاعل"]), (o, ["مفعول به"]))
            add("نثر: تقديم المفعول", (p, ["فعل ماضٍ"]), (o, ["مفعول به"]), (s, ["فاعل"]))
            add("نثر: مبتدأ وخبر فعلي", (s, ["مبتدأ"]), (p, ["ش:خبر", "فعل ماضٍ"]), (o, ["مفعول به"]))
            for suf in ("ْتُ", "ْتَ", "ْنَا"):          # فَعَلْتُ، فَعَلْتَ، فَعَلْنَا
                add("نثر: فعل وفاعل متصل", (p[:-1] + suf, ["فاعل", "فعل ماضٍ"]), (o, ["مفعول به"]))
            add("نائب فاعل", (ps, ["فعل ماضٍ مبني للمجهول"]), (with_case(o, "ُ"), ["نائب فاعل"]))
            for o2 in objs:
                if o2 != o:
                    add("عطف اسم منصوب (مقابل المعية)", (p, ["فعل ماضٍ"]), (s, ["فاعل"]), (o, ["مفعول به"]), ("وَ" + o2, ["حرف عطف", "اسم معطوف"]))
            # لام الأمر في صدر الكلام، وبعد الفاء والواو
            add("لام الأمر", ("لِ" + jazm(m3, s), ["حرف جزم", "فعل مضارع"]), (s, ["فاعل"]), (o, ["مفعول به"]))
            add("لام الأمر", ("فَلْ" + jazm(m3, s), ["حرف جزم", "حرف عطف", "فعل مضارع"]), (s, ["فاعل"]), (o, ["مفعول به"]))
            # لام التعليل في أثناء الكلام
            for v, v1 in MOTION[:4]:
                add("لام التعليل", (v, ["فعل ماضٍ"]), (s, ["فاعل"]), ("لِ" + m3 + "َ", ["حرف جر", "فعل مضارع"]), (o, ["مفعول به"]))
                add("لام التعليل", (v1, ["فاعل", "فعل ماضٍ"]), ("لِأَ" + m3[2:] + "َ", ["حرف جر", "فعل مضارع"]), (o, ["مفعول به"]))
    for (p, ps, m3, m2, imp, objs) in VERBS:
        for o in objs:
            for r in RESULT:
                add("فاء السببية", (jazm(imp, o), ["فعل أمر"]), (o, ["مفعول به"]), ("فَ" + r, ["حرف غير عامل", "فعل مضارع"]))
            for (_, _, _, m2b, imp2, objs2) in VERBS:
                if m2b == m2:
                    continue
                for o2 in objs2:
                    # «لا تفعلْ كذا وتفعلَ كذا»: النصب معية، والجزم عطف (نهي عن كلٍّ منهما)؛ والنص بلا شكل يحتملهما
                    add("واو المعية", ("لَا", ["حرف جزم"]), (jazm(m2, o), ["فعل مضارع"]), (o, ["مفعول به"]),
                        ("وَ" + m2b + "َ", ["حرف غير عامل", "فعل مضارع"]), (o2, ["مفعول به"]))
                    add("عطف فعل مجزوم (مقابل المعية)", ("لَا", ["حرف جزم"]), (jazm(m2, o), ["فعل مضارع"]), (o, ["مفعول به"]),
                        ("وَ" + jazm(m2b, o2), ["حرف عطف", "فعل مضارع"]), (o2, ["مفعول به"]))
                    add("عطف (مقابل السببية)", (jazm(imp, o), ["فعل أمر"]), (o, ["مفعول به"]),
                        ("وَ" + jazm(imp2, o2), ["حرف عطف", "فعل أمر"]), (o2, ["مفعول به"]))
    for (v, _), s, h in itertools.product(MOTION, SUBJ, HAL):
        add("حال", (v, ["فعل ماضٍ"]), (s, ["فاعل"]), (h, ["حال"]))
    return out


def gold_words(path):
    words = set()
    for l in open(path, encoding="utf-8"):
        for w in json.loads(l)["text"].split():
            words.add(bare(w))
    return words - FUNCTION_WORDS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path.home() / ".sarf" / "corpora" / "gen_irab.jsonl"))
    ap.add_argument("--per", type=int, default=250, help="أقصى عدد للجمل من كل ظاهرة")
    ap.add_argument("--gold", default=str(Path(__file__).resolve().parent / "eval" / "gold_irab" / "gold.jsonl"))
    a = ap.parse_args()
    G = gold_words(a.gold)
    rnd = random.Random(7)
    by = {}
    for kind, ws in gen():
        by.setdefault(kind, []).append(ws)
    out, seen = [], set()   # المكرّر يُعرف بالنص المشكول: «وتتركَ» و«وتتركِ» نصّهما المجرّد واحد، وهما المقابلان المقصودان
    for kind, items in by.items():
        rnd.shuffle(items)
        n = 0
        for ws in items:
            plain = " ".join(bare(w) for w, _ in ws)
            key = " ".join(w for w, _ in ws)
            if key in seen:
                continue
            leak = [bare(w) for w, _ in ws if bare(w) in G or bare(w)[1:] in G and bare(w)[:1] in "وفل"]
            assert not leak, (kind, plain, leak)          # لا كلمة من المجموعة الذهبية
            seen.add(key)
            out.append({"kind": kind, "words": [w for w, _ in ws], "labels": [ls for _, ls in ws]})
            n += 1
            if n >= a.per:
                break
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        for d in out:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    from collections import Counter
    print(len(out), "جملة →", a.out)
    for k, n in Counter(d["kind"] for d in out).most_common():
        print(f"  {k}: {n}")


if __name__ == "__main__":
    main()
